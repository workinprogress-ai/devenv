// attribution-patterns: the shared matcher that rejects AI attribution lines in
// commit messages and in PR/issue bodies. Patterns are anchored to the trailer
// or footer position of a line, so text that merely discusses attribution passes.
import { describe, expect, it } from "vitest";
import {
  AI_EMAIL_DOMAINS,
  AI_IDENTITIES,
  AMBIGUOUS_IDENTITIES,
  attributionRejection,
  findAttribution,
  TRAILER_KEYS,
} from "../../lib/core/attribution-patterns.ts";

const rules = (text: string, extra?: string[]): Array<[number, string]> =>
  findAttribution(text, extra === undefined ? {} : { extraIdentities: extra }).map((h) => [h.line, h.rule]);

describe("core/attribution-patterns", () => {
  it("lists the default trailer keys and AI identities", () => {
    expect([...TRAILER_KEYS]).toEqual(["co-authored-by", "generated-by", "assisted-by", "authored-by", "created-by", "signed-off-by"]);
    expect([...AI_IDENTITIES]).toEqual([
      "claude",
      "anthropic",
      "copilot",
      "chatgpt",
      "openai",
      "codex",
      "gemini",
      "cursor",
      "aider",
      "devin",
      "windsurf",
      "gpt",
    ]);
  });

  it("separates identities that are also people's names, and lists the vendor address domains", () => {
    expect([...AMBIGUOUS_IDENTITIES]).toEqual(["claude", "codex", "gemini", "cursor", "aider", "devin"]);
    for (const id of AMBIGUOUS_IDENTITIES) expect((AI_IDENTITIES as readonly string[]).includes(id), id).toBe(true);
    expect([...AI_EMAIL_DOMAINS]).toEqual(["anthropic.com", "openai.com", "cursor.com"]);
  });

  describe("does not flag a human whose name matches an identity", () => {
    const humans = [
      "Co-Authored-By: Devin Smith <devin.smith@corp.com>",
      "Created-by: Gemini Rossi <g@example.com>",
      "Authored-by: Aider Jones <a@example.com>",
      "Co-Authored-By: Claude Dupont <claude@corp.fr>",
      "Co-Authored-By: Alice <alice@example.com> (works at Cursor Inc)",
      "Co-Authored-By: Alice <alice@claude-corp.com>",
      "Co-Authored-By: Jules Verne <jules@example.com>",
      "Signed-off-by: Cody Codex <cody@example.com>",
    ];
    for (const line of humans) {
      it(line, () => expect(rules(`fix: x\n\n${line}`)).toEqual([]));
    }
    it("passes a footer-looking sentence about a person", () => {
      expect(rules("Created by Codex Smith\nGenerated by Claude Dupont last year")).toEqual([]);
    });
    it("passes a sentence that merely starts like a footer", () => {
      expect(rules("Generated by Claude Code is banned here\nMade with Cursor in mind")).toEqual([]);
    });
  });

  describe("still flags an AI identity with qualifiers or a vendor address", () => {
    const ai = [
      "Co-Authored-By: Claude Opus 4 <x@example.com>",
      "Co-Authored-By: Gemini 2.5 Pro <x@example.com>",
      "Co-Authored-By: Cursor Agent <x@example.com>",
      "Co-Authored-By: Devin AI <x@example.com>",
      "Co-Authored-By: GitHub Copilot <x@example.com>",
      "Co-Authored-By: GPT-5 <x@example.com>",
      "Co-Authored-By: Automation <bot@anthropic.com>",
      "Co-Authored-By: Automation <bot@mail.anthropic.com>",
      "Signed-off-by: Claude <noreply@anthropic.com>",
    ];
    for (const line of ai) {
      it(line, () => expect(rules(`fix: x\n\n${line}`)).toEqual([[3, "trailer"]]));
    }
  });

  describe("cannot be switched off by an unclosed fence", () => {
    const trailer = "Co-Authored-By: Claude <noreply@anthropic.com>";
    it("checks lines after a fence that never closes", () => {
      expect(rules(`text\n\`\`\`\nsome code\n${trailer}`)).toEqual([[4, "trailer"]]);
    });
    it("does not let a different fence character close a fence", () => {
      expect(rules(`~~~\n${trailer}\n\`\`\`\n${trailer}`)).toEqual([
        [2, "trailer"],
        [4, "trailer"],
      ]);
    });
    it("needs a closing fence at least as long as the opener", () => {
      expect(rules(`\`\`\`\`\n${trailer}\n\`\`\`\n${trailer}`)).toEqual([
        [2, "trailer"],
        [4, "trailer"],
      ]);
    });
    it("still hides a properly closed fence", () => {
      expect(rules(`\`\`\`\n${trailer}\n\`\`\`\n`)).toEqual([]);
    });
  });

  describe("sees through cheap disguises", () => {
    it("ignores invisible format characters inside the key and the name", () => {
      expect(rules("Co​-Authored-By: Claude <a@example.com>")).toEqual([[1, "trailer"]]);
      expect(rules("Co-Authored-By: Cl​aude <a@example.com>")).toEqual([[1, "trailer"]]);
      expect(rules("﻿Co-Authored-By: Claude <a@example.com>")).toEqual([[1, "trailer"]]);
    });
    it("tolerates markdown emphasis around the key", () => {
      expect(rules("**Co-Authored-By:** Claude <a@example.com>")).toEqual([[1, "trailer"]]);
      expect(rules("**Co-Authored-By**: Claude <a@example.com>")).toEqual([[1, "trailer"]]);
      expect(rules("__Co-Authored-By:__ Claude")).toEqual([[1, "trailer"]]);
    });
    it("accepts a colon after the footer verb", () => {
      expect(rules("Generated by: Claude Code")).toEqual([[1, "footer"]]);
    });
    it("ignores a decoration after the footer name", () => {
      expect(rules("Generated with Claude Code 🤖")).toEqual([[1, "footer"]]);
    });
  });

  describe("rejects trailer lines naming an AI identity", () => {
    const lines = [
      "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>",
      "Co-authored-by: Claude <noreply@anthropic.com>",
      "co-authored-by: copilot <175728472+Copilot@users.noreply.github.com>",
      "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
      "Co-authored-by: ChatGPT <noreply@openai.com>",
      "Generated-by: Codex",
      "Assisted-by: Gemini 3",
      "Authored-by: Devin",
      "CREATED-BY: Aider (gpt-5)",
    ];
    for (const line of lines) {
      it(line, () => {
        expect(rules(`fix: a change\n\nBody text.\n\n${line}`)).toEqual([[5, "trailer"]]);
      });
    }
  });

  describe("rejects footer lines that start with a generated-with phrase", () => {
    const lines = [
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "Generated with Claude Code",
      "generated by GitHub Copilot",
      "Created using ChatGPT",
      "Made with Cursor",
      "✨ Assisted by Codex",
    ];
    for (const line of lines) {
      it(line, () => {
        expect(rules(`Summary of the change.\n\n${line}\n`)).toEqual([[3, "footer"]]);
      });
    }
  });

  it("rejects the full pair Claude Code appends to a commit message", () => {
    const message = [
      "minor(tools): add a thing",
      "",
      "Body.",
      "",
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "",
      "Co-Authored-By: Claude <noreply@anthropic.com>",
      "Devenv-Action: none",
    ].join("\n");
    expect(rules(message)).toEqual([
      [5, "footer"],
      [7, "trailer"],
    ]);
  });

  describe("passes text that does not attribute the work to an AI", () => {
    it("accepts a human co-author and other trailers", () => {
      const message = "fix: x\n\nCo-authored-by: Claudia Smith <claudia@example.com>\nSigned-off-by: A Person <a@example.com>\nDevenv-Action: none";
      expect(rules(message)).toEqual([]);
    });

    it("accepts a commit message that discusses attribution", () => {
      const message = [
        "minor(tools): add AI attribution matcher",
        "",
        'Rejects Co-Authored-By trailers that name an AI identity and "Generated with Claude Code" footers.',
        "Messages that merely discuss attribution, like this one, pass. A trailer such as",
        "Co-Authored-By without a colon and an identity is not flagged either.",
        "Generated by hand from the policy list.",
        "",
        "Devenv-Action: none",
      ].join("\n");
      expect(rules(message)).toEqual([]);
    });

    it("accepts a PR body that quotes examples in code, quotes and indented blocks", () => {
      const body = [
        "## Summary",
        "",
        "Blocks lines like `Co-Authored-By: Claude <noreply@anthropic.com>` in commit messages.",
        "",
        "```text",
        "Co-Authored-By: Claude <noreply@anthropic.com>",
        "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        "```",
        "",
        "~~~",
        "Generated by Copilot",
        "~~~",
        "",
        "> Co-Authored-By: Claude <noreply@anthropic.com>",
        "",
        "    Co-Authored-By: Claude <noreply@anthropic.com>",
        "\tGenerated with Claude Code",
        "",
        "## Test plan",
        "- [x] unit tests",
      ].join("\n");
      expect(rules(body)).toEqual([]);
    });

    it("accepts a quoted footer and a quoted trailer", () => {
      expect(rules("> Generated with Claude Code\n>   Co-Authored-By: Claude <n@anthropic.com>\n")).toEqual([]);
    });

    it("resumes matching after a fenced block closes", () => {
      const body = "```\nGenerated with Claude Code\n```\n\nGenerated with Claude Code\n";
      expect(rules(body)).toEqual([[5, "footer"]]);
    });

    it("does not match an identity inside a longer word", () => {
      expect(rules("Co-authored-by: Claudette <c@example.com>\nGenerated with Geminiology")).toEqual([]);
    });
  });

  it("matches case-insensitively and across CRLF input", () => {
    expect(rules("x\r\nCO-AUTHORED-BY: CLAUDE <n@anthropic.com>\r\n")).toEqual([[2, "trailer"]]);
  });

  it("returns hits in order with 1-based lines and trimmed text", () => {
    const hits = findAttribution("a\nGenerated with Claude Code  \nb\nGenerated-by: Codex\n");
    expect(hits).toEqual([
      { line: 2, rule: "footer", text: "Generated with Claude Code" },
      { line: 4, rule: "trailer", text: "Generated-by: Codex" },
    ]);
  });

  it("lets a fork add identities without losing the defaults", () => {
    expect(rules("Co-authored-by: Acme Bot <bot@acme.example>", [])).toEqual([]);
    expect(rules("Co-authored-by: Acme Bot <bot@acme.example>", ["acme bot"])).toEqual([[1, "trailer"]]);
    expect(rules("Generated with Acme Bot", ["acme bot"])).toEqual([[1, "footer"]]);
    expect(rules("Co-authored-by: Claude <n@anthropic.com>", ["acme bot"])).toEqual([[1, "trailer"]]);
  });

  it("escapes regex characters in added identities", () => {
    expect(rules("Generated with c++ bot", ["c++ bot"])).toEqual([[1, "footer"]]);
    expect(rules("Generated with cxx bot", ["c++ bot"])).toEqual([]);
  });

  describe("attributionRejection", () => {
    it("is empty when there are no hits", () => {
      expect(attributionRejection([], "commit message")).toBe("");
    });

    it("tells the author what to do, quoting each offending line", () => {
      const hits = findAttribution("x\n\nGenerated with Claude Code\nCo-Authored-By: Claude <n@anthropic.com>");
      const text = attributionRejection(hits, "commit message");
      expect(text).toMatch(/AI attribution/);
      expect(text).toMatch(/commit message/);
      expect(text).toMatch(/Remove/);
      expect(text).toContain("line 3: Generated with Claude Code");
      expect(text).toContain("line 4: Co-Authored-By: Claude <n@anthropic.com>");
      expect(text).toMatch(/code span or fenced block/);
    });

    it("names the kind of text being checked", () => {
      const hits = findAttribution("Generated with Claude Code");
      expect(attributionRejection(hits, "pull request body")).toMatch(/pull request body/);
    });

    it("chooses 'a' or 'an' to match the subject", () => {
      const hits = findAttribution("Generated with Claude Code");
      expect(attributionRejection(hits, "pull request body")).toContain("not allowed in a pull request body");
      expect(attributionRejection(hits, "issue body")).toContain("not allowed in an issue body");
      expect(attributionRejection(hits, "artifact body")).toContain("not allowed in an artifact body");
    });
  });
});
